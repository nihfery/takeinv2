CREATE FUNCTION sync_booking_staff_slots() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE booking_staff_slots
       SET active=NEW.status IN ('pending','pending_hold','pending_payment','confirmed','waiting','checked_in','in_progress','inprogress'),
           staff_id=CASE WHEN source_key='booking' THEN NEW.staff_id ELSE staff_id END,
           starts_at=CASE WHEN source_key='booking' THEN NEW.starts_at ELSE starts_at END,
           ends_at=CASE WHEN source_key='booking' THEN NEW.ends_at ELSE ends_at END,
           updated_at=now()
     WHERE booking_id=NEW.id;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER bookings_sync_staff_slots
AFTER UPDATE OF status,staff_id,starts_at,ends_at ON bookings
FOR EACH ROW EXECUTE FUNCTION sync_booking_staff_slots();

