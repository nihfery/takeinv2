CREATE TABLE booking_staff_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    participant_id BIGINT REFERENCES booking_participants(id) ON DELETE CASCADE,
    source_key TEXT NOT NULL,
    staff_id BIGINT NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(booking_id, source_key),
    CHECK(ends_at > starts_at)
);

INSERT INTO booking_staff_slots(booking_id,participant_id,source_key,staff_id,starts_at,ends_at,active)
SELECT p.booking_id,p.id,'participant:'||p.id,p.provider_staff_id,p.starts_at,p.ends_at,
       b.status IN ('pending','pending_hold','pending_payment','confirmed','waiting','checked_in','in_progress','inprogress')
FROM booking_participants p
JOIN bookings b ON b.id=p.booking_id
WHERE p.provider_staff_id IS NOT NULL AND p.starts_at IS NOT NULL AND p.ends_at IS NOT NULL;

INSERT INTO booking_staff_slots(booking_id,source_key,staff_id,starts_at,ends_at,active)
SELECT b.id,'booking',b.staff_id,b.starts_at,b.ends_at,
