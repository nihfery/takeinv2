CREATE TABLE booking_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    service_id BIGINT NOT NULL,
    service_title TEXT NOT NULL,
    price NUMERIC(12,2) NOT NULL DEFAULT 0,
    estimated_duration INTEGER NOT NULL DEFAULT 30,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE booking_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    position SMALLINT NOT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT false,
    name TEXT NOT NULL,
    phone VARCHAR(30),
    email TEXT,
    gender VARCHAR(20),
    age_group VARCHAR(20),
    description TEXT,
    provider_staff_id BIGINT,
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    total_duration INTEGER NOT NULL DEFAULT 0,
    total_price NUMERIC(12,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(booking_id, position),
    CHECK(ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)
);

CREATE TABLE booking_participant_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_participant_id BIGINT NOT NULL REFERENCES booking_participants(id) ON DELETE CASCADE,
    service_id BIGINT NOT NULL,
    service_title TEXT NOT NULL,
    price NUMERIC(12,2) NOT NULL DEFAULT 0,
    estimated_duration INTEGER NOT NULL DEFAULT 30,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE idempotency_records (
    customer_id BIGINT NOT NULL,
    idempotency_key TEXT NOT NULL,
    request_hash TEXT NOT NULL,
    resource_id BIGINT,
    response_status INTEGER,
    response_body JSONB,
    locked_until TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(customer_id, idempotency_key)
);

CREATE TABLE payment_projection (
    payment_id BIGINT PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    status TEXT NOT NULL,
    event_id UUID NOT NULL UNIQUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

