CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code TEXT NOT NULL UNIQUE,
    provider_id BIGINT NOT NULL,
    customer_id BIGINT,
    branch_id BIGINT,
    staff_id BIGINT,
    booking_type TEXT NOT NULL DEFAULT 'scheduled' CHECK (booking_type IN ('scheduled', 'queue', 'walk_in', 'manual', 'group')),
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','pending','pending_hold','expired_hold','payment_expired','inprogress','completed','order_completed','refund_completed','provider_cancelled','customer_cancelled','rescheduled','pending_payment','confirmed','waiting','checked_in','in_progress','cancelled','no_show')),
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    actual_started_at TIMESTAMPTZ,
    actual_ended_at TIMESTAMPTZ,
    total_duration INTEGER NOT NULL DEFAULT 0 CHECK (total_duration >= 0),
    total_price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total_price >= 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'IDR',
    customer_name TEXT,
    customer_phone TEXT,
    participant_count SMALLINT NOT NULL DEFAULT 1 CHECK (participant_count > 0),
    notes TEXT,
    queue_number INTEGER,
    checked_in_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    held_at TIMESTAMPTZ,
    hold_expires_at TIMESTAMPTZ,
    expired_at TIMESTAMPTZ,
    idempotency_key TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK(ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)
);
CREATE UNIQUE INDEX bookings_customer_idempotency_idx ON bookings(customer_id, idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX bookings_customer_time_idx ON bookings(customer_id, created_at DESC);
CREATE INDEX bookings_provider_branch_time_idx ON bookings(provider_id, branch_id, starts_at);
